// Builds the API bundle and the web app, then commits them to the `deploy` branch and pushes it.
// cPanel's Git Version Control clones that branch on the server, and its .cpanel.yml (made from
// scripts/cpanel.yml) copies the files into place, installs dependencies, runs migrations and
// restarts the app when you click "Deploy HEAD Commit". Nothing is built on the server.
//
// Usage: npm run deploy:git [-- --no-push] [--api-origin https://…] [--home /home2/nevanhan] [--node 22]
//                           [--web-root svc.nevanhandicraft.com.np]
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const { values: args } = parseArgs({
  options: {
    'api-origin': { type: 'string', default: 'https://api.nevanhandicraft.com.np' },
    // The account's home directory on the server (`echo $HOME` in cPanel Terminal).
    home: { type: 'string', default: '/home2/nevanhan' },
    node: { type: 'string', default: '22' },
    'web-root': { type: 'string', default: 'svc.nevanhandicraft.com.np' },
    'no-push': { type: 'boolean', default: false },
  },
});
const apiOrigin = new URL(args['api-origin']).origin;

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const apiOut = path.join(root, 'deploy/api');
const webDist = path.join(root, 'apps/web/dist');
const worktree = path.join(root, 'deploy/branch');
const branch = 'deploy';

const node = (script, extra = []) =>
  execFileSync(process.execPath, [path.join(root, 'scripts', script), ...extra], {
    cwd: root,
    stdio: 'inherit',
  });
// Quiet git: returns stdout, throws on a non-zero exit.
const git = (gitArgs, cwd = root) =>
  execFileSync('git', gitArgs, {
    cwd,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
  }).trim();
// Git whose output the user should see.
const gitShow = (gitArgs, cwd = root) => execFileSync('git', gitArgs, { cwd, stdio: 'inherit' });
const gitOk = (gitArgs, cwd = root) => {
  try {
    execFileSync('git', gitArgs, { cwd, stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
};

// 1. Build with the existing bundle scripts (deploy/api and apps/web/dist; the zips are a by-product).
node('build-api-deploy.mjs');
node('build-web-deploy.mjs', ['--api-origin', apiOrigin]);

// 2. Check out the deploy branch in a worktree under the gitignored deploy/ folder.
const sha = git(['rev-parse', '--short', 'HEAD']);
const dirty = git(['status', '--porcelain', '--untracked-files=no']) !== '';
const source = `${sha}${dirty ? ' (with uncommitted changes)' : ''}`;

if (existsSync(worktree)) gitOk(['worktree', 'remove', '--force', worktree]);
rmSync(worktree, { recursive: true, force: true });
git(['worktree', 'prune']);
gitOk(['fetch', 'origin', branch]); // fails harmlessly before the first push
if (gitOk(['rev-parse', '--verify', '--quiet', `origin/${branch}`])) {
  gitShow(['worktree', 'add', '-B', branch, worktree, `origin/${branch}`]);
} else if (gitOk(['rev-parse', '--verify', '--quiet', `refs/heads/${branch}`])) {
  gitShow(['worktree', 'add', worktree, branch]);
} else {
  gitShow(['worktree', 'add', '--detach', worktree]);
  git(['checkout', '-q', '--orphan', branch], worktree);
  git(['rm', '-rfq', '.'], worktree);
}

// 3. Replace the branch contents with this build.
for (const entry of readdirSync(worktree)) {
  if (entry !== '.git') rmSync(path.join(worktree, entry), { recursive: true, force: true });
}
cpSync(apiOut, path.join(worktree, 'api'), { recursive: true });
cpSync(webDist, path.join(worktree, 'web'), { recursive: true });

// Built files are stored byte for byte: no CRLF conversion on Windows checkouts, and no warnings.
writeFileSync(path.join(worktree, '.gitattributes'), '* -text\n');

const home = args.home.replace(/\/+$/, '');
const cpanelYml = readFileSync(path.join(root, 'scripts/cpanel.yml'), 'utf8')
  .replaceAll('{{HOME}}', home)
  .replaceAll('{{NODE}}', args.node)
  .replaceAll('{{WEB_ROOT}}', args['web-root']);
writeFileSync(path.join(worktree, '.cpanel.yml'), cpanelYml);

const date = new Date().toISOString().slice(0, 16).replace('T', ' ') + ' UTC';
writeFileSync(
  path.join(worktree, 'README.md'),
  `# SVI exam app: deploy branch

Generated by \`npm run deploy:git\` from commit ${source}. Do not edit by hand:
the next run replaces everything here.

- \`api/\`: the API bundle (what \`deploy/svi-api.zip\` holds), copied to \`${home}/svi-api\`.
- \`web/\`: the built web app for the API at ${apiOrigin}, copied to \`${home}/${args['web-root']}\`.
- \`.cpanel.yml\`: run by cPanel → Git Version Control → Pull or Deploy → Deploy HEAD Commit.
`,
);

// 4. Commit and push when something changed.
git(['add', '-A', '-f', '.'], worktree);
if (gitOk(['diff', '--cached', '--quiet'], worktree)) {
  console.log(`\nNothing changed since the last deploy commit; ${branch} is up to date.`);
} else {
  git(['commit', '-q', '-m', `Deploy ${source}, ${date}`], worktree);
  gitShow(['log', '-1', '--shortstat', '--format=%h %s'], worktree);
  if (args['no-push'])
    console.log(`\nNot pushed (--no-push). Branch ${branch} is committed locally.`);
  else gitShow(['push', '-u', 'origin', branch], worktree);
}

try {
  git(['worktree', 'remove', '--force', worktree]);
} catch {
  console.warn(`Could not remove ${worktree}; delete it by hand and run "git worktree prune".`);
}

if (!args['no-push']) {
  console.log(
    `\nNext, in cPanel → Git Version Control → Manage → Pull or Deploy:\n` +
      `  1. Update from Remote\n  2. Deploy HEAD Commit\n` +
      `Then check ${apiOrigin}/api/v1/health.`,
  );
}
