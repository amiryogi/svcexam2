// Builds the web app for static hosting on the cPanel server (e.g. svc.nevanhandicraft.com.np), next to
// the API on its own subdomain: deploy/svi-web.zip, to extract into the subdomain's document root.
// The browser calls the API directly (CORS, see apps/api/src/middleware/cors.ts), so there is no proxy
// for the hosting firewall to block. The .htaccess files replace what apps/web/vercel.json did on Vercel:
// single-page-app fallback, security headers and caching.
//
// Usage: npm run build:web-deploy [-- --api-origin https://api.nevanhandicraft.com.np]
import { execFileSync, execSync } from 'node:child_process';
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const { values: args } = parseArgs({
  options: { 'api-origin': { type: 'string', default: 'https://api.nevanhandicraft.com.np' } },
});
const apiOrigin = new URL(args['api-origin']).origin;

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'apps/web/dist');
const zip = path.join(root, 'deploy/svi-web.zip');

rmSync(dist, { recursive: true, force: true });
execSync('npm run build -w @svi/web', {
  cwd: root,
  stdio: 'inherit',
  env: { ...process.env, VITE_API_ORIGIN: apiOrigin },
});

const csp = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  `img-src 'self' data: blob: ${apiOrigin}`,
  `connect-src 'self' ${apiOrigin}`,
  "font-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ');

writeFileSync(
  path.join(dist, '.htaccess'),
  `# Generated by scripts/build-web-deploy.mjs (API: ${apiOrigin}).
Options -Indexes
DirectoryIndex index.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteCond %{HTTPS} !=on
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]
  # Real files (index.html, assets, favicon) are served as they are; every other path is an app route.
  RewriteCond %{REQUEST_FILENAME} -f [OR]
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteRule ^ - [L]
  RewriteRule ^ index.html [L]
</IfModule>

<IfModule mod_headers.c>
  Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains"
  Header always set X-Content-Type-Options "nosniff"
  Header always set X-Frame-Options "DENY"
  Header always set Referrer-Policy "same-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
  Header always set X-Robots-Tag "noindex, nofollow"
  Header always set Content-Security-Policy "${csp}"
  # The app shell must always be revalidated so a new deploy is picked up at once.
  Header set Cache-Control "no-cache"
</IfModule>
`,
);
// Built assets have content hashes in their names, so they can be cached for good.
writeFileSync(
  path.join(dist, 'assets', '.htaccess'),
  `<IfModule mod_headers.c>
  Header set Cache-Control "public, max-age=31536000, immutable"
</IfModule>
`,
);

mkdirSync(path.dirname(zip), { recursive: true });
rmSync(zip, { force: true });
const entries = readdirSync(dist);
// Windows' own bsdtar writes zips (Git Bash's GNU tar, which may come first in PATH, cannot).
if (process.platform === 'win32') {
  const tar = path.join(process.env.SystemRoot ?? 'C:\\Windows', 'System32', 'tar.exe');
  execFileSync(tar, ['-a', '-cf', zip, ...entries], { cwd: dist, stdio: 'inherit' });
} else execFileSync('zip', ['-qr', zip, ...entries], { cwd: dist, stdio: 'inherit' });

console.log(`\nWeb bundle ready (API: ${apiOrigin}):\n  ${zip}\nExtract it into the subdomain's document root.`);
